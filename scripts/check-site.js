#!/usr/bin/env node
/**
 * Verifies a built site before it is deployed:
 *   - every internal link and asset reference resolves to a file in dist/
 *   - every in-page anchor (#id) exists on its target page
 *   - every legacy redirect target exists
 *   - the pages every area needs are present
 *
 * Usage: node scripts/check-site.js [--dir dist]
 * Exit code 1 on any broken reference.
 */
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './lib/history.js';

const argv = process.argv.slice(2);
const dir = path.resolve(argv.includes('--dir') ? argv[argv.indexOf('--dir') + 1] : path.join(ROOT, 'dist'));
const base = ('/' + (process.env.BASE_PATH || '/').replace(/^\/+|\/+$/g, '') + '/').replace(/\/+/g, '/');

const htmlFiles = [];
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    // The c8 report is generated by c8 itself and only links within itself.
    if (e.isDirectory() && p !== path.join(dir, 'coverage', 'report')) walk(p);
    else if (e.isFile() && e.name.endsWith('.html')) htmlFiles.push(p);
  }
})(dir);

const idCache = new Map();
function idsOf(file) {
  if (!idCache.has(file)) {
    const html = fs.readFileSync(file, 'utf8');
    idCache.set(file, new Set([...html.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1])));
  }
  return idCache.get(file);
}

function resolve(urlPath) {
  if (!urlPath.startsWith(base)) return null;
  let rel = decodeURIComponent(urlPath.slice(base.length));
  let file = path.join(dir, rel);
  if (rel === '' || rel.endsWith('/')) file = path.join(file, 'index.html');
  return fs.existsSync(file) && fs.statSync(file).isFile() ? file : null;
}

const problems = [];
let checked = 0;
for (const file of htmlFiles) {
  const html = fs.readFileSync(file, 'utf8');
  const pageUrl = base + path.relative(dir, file).split(path.sep).join('/').replace(/index\.html$/, '');
  for (const m of html.matchAll(/\s(?:href|src)="([^"]+)"/g)) {
    const raw = m[1].replace(/&amp;/g, '&');
    if (/^(https?:|mailto:|data:|javascript:)/.test(raw)) continue;
    checked++;
    if (raw === '#') {
      problems.push(`${pageUrl}: empty link "#"`);
      continue;
    }
    const [pathPart, hash] = raw.split('#');
    const target = pathPart ? resolve(pathPart.split('?')[0]) : file;
    if (!target) {
      problems.push(`${pageUrl}: broken link ${raw}`);
      continue;
    }
    if (hash && target.endsWith('.html') && !idsOf(target).has(hash)) problems.push(`${pageUrl}: missing anchor ${raw}`);
  }
}

// Legacy redirects (embedded in 404.html).
const notFound = path.join(dir, '404.html');
let redirects = {};
if (fs.existsSync(notFound)) {
  const m = fs.readFileSync(notFound, 'utf8').match(/var map = (\{.*?\});/s);
  redirects = m ? JSON.parse(m[1]) : {};
  for (const [from, to] of Object.entries(redirects)) {
    if (/^https?:/.test(to)) continue;
    const [p] = to.split(/[?#]/);
    if (!resolve(base + p)) problems.push(`redirect ${from} -> ${to}: target missing`);
  }
} else problems.push('404.html missing');

for (const required of ['index.html', 'docs/index.html', 'coverage/index.html', 'benchmarks/index.html', 'benchmarks/results.json', 'assets/styles.css', 'assets/app.js', 'assets/search-index.json', 'data/coverage-history.json', 'data/benchmarks-history.json', '.nojekyll']) {
  if (!fs.existsSync(path.join(dir, required))) problems.push(`required file missing: ${required}`);
}

console.log(`Checked ${checked} references in ${htmlFiles.length} pages, ${Object.keys(redirects).length} legacy redirects.`);
if (problems.length) {
  console.error(`${problems.length} problem(s):\n` + problems.slice(0, 50).map((p) => `  ${p}`).join('\n'));
  if (problems.length > 50) console.error(`  … and ${problems.length - 50} more`);
  process.exit(1);
}
console.log('No broken references.');
